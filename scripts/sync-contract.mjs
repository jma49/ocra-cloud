#!/usr/bin/env node
// Copies @open-cr-agent/cloud-contract from an Open-CR-Agent checkout into
// src/contract/, at the engine commit contract.lock pins. The copy stands in
// for the npm package until its first publish; then this script, the lock
// and the CI check give way to an exact dependency.
//
// Usage: node scripts/sync-contract.mjs <engine checkout> [--check] [--commit <sha>]
//   --commit  copy that commit instead, and pin it in contract.lock
//   --check   change nothing; fail when src/contract/ differs from the copy
//
// The files are read from the commit with git, not from the checkout's
// working tree, so an uncommitted change there never lands here.
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const lockPath = join(root, "contract.lock");
const target = join(root, "src", "contract");
const PACKAGE = "packages/cloud-contract";

const args = process.argv.slice(2);
const check = args.includes("--check");
const commitAt = args.indexOf("--commit");
const engine = args.find((a, i) => !a.startsWith("--") && (commitAt < 0 || i !== commitAt + 1));
if (!engine) {
  console.error(
    "usage: node scripts/sync-contract.mjs <engine checkout> [--check] [--commit <sha>]",
  );
  process.exit(2);
}

const git = (...a) => execFileSync("git", ["-C", engine, ...a], { encoding: "utf8" });
const wanted = commitAt >= 0 ? args[commitAt + 1] : readFileSync(lockPath, "utf8").trim();
const commit = git("rev-parse", "--verify", `${wanted}^{commit}`).trim();

// Sources and fixtures; the package's own tests stay in the engine.
const files = git("ls-tree", "-r", "--name-only", commit, `${PACKAGE}/src`, `${PACKAGE}/fixtures`)
  .split("\n")
  .filter((f) => f && !f.endsWith(".test.ts") && !f.endsWith(".fakes.ts"));
if (!files.some((f) => f.endsWith("/src/index.ts"))) {
  console.error(`${commit} has no ${PACKAGE}/src/index.ts`);
  process.exit(1);
}

const header = `// Generated by scripts/sync-contract.mjs from @open-cr-agent/cloud-contract
// at Open-CR-Agent ${commit}. Do not edit: change the engine, then sync.
`;
const copy = new Map(
  files.map((f) => {
    const out = f.slice(PACKAGE.length + 1).replace(/^src\//, "");
    const text = git("show", `${commit}:${f}`);
    return [out, f.endsWith(".ts") ? `${header}\n${text}` : text];
  }),
);

function present(dir) {
  const out = new Map();
  let names = [];
  try {
    names = readdirSync(dir, { recursive: true, withFileTypes: true });
  } catch {
    return out;
  }
  for (const d of names) {
    if (!d.isFile()) continue;
    const path = join(d.parentPath, d.name);
    out.set(relative(dir, path), readFileSync(path, "utf8"));
  }
  return out;
}

if (check) {
  const have = present(target);
  const differ = [...new Set([...have.keys(), ...copy.keys()])]
    .filter((f) => have.get(f) !== copy.get(f))
    .sort();
  const pinned = readFileSync(lockPath, "utf8").trim();
  if (pinned !== commit) differ.push(`contract.lock (${pinned}, not ${commit})`);
  if (differ.length > 0) {
    console.error(
      `src/contract/ is not the contract at ${commit}:\n  ${differ.join("\n  ")}\n` +
        "run node scripts/sync-contract.mjs <engine checkout>, and change the engine, not the copy",
    );
    process.exit(1);
  }
  console.log(`src/contract/ is the contract at ${commit}`);
} else {
  rmSync(target, { recursive: true, force: true });
  for (const [file, text] of copy) {
    mkdirSync(dirname(join(target, file)), { recursive: true });
    writeFileSync(join(target, file), text);
  }
  writeFileSync(lockPath, `${commit}\n`);
  console.log(`copied the contract at ${commit} into src/contract/ (${copy.size} files)`);
}
