// Writes src/engine-schemas.ts: the JSON Schemas the engine reads a
// repository's .ocra/config.json and .ocra/rules.json with, taken from the
// installed engine packages, so the Worker checks a console edit without
// loading the engine. Run with Node after bumping them:
// node scripts/engine-schemas.ts (test-node/engine-schemas.test.ts fails until then).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { configJsonSchema } from "@open-cr-agent/cli/internal";
import { repoRuleSchema } from "@open-cr-agent/core/internal";
import { z } from "zod";

const target = new URL("../src/engine-schemas.ts", import.meta.url);
const rules = z.toJSONSchema(z.object({ rules: z.array(repoRuleSchema) }), {
  target: "draft-2020-12",
  io: "input",
});
const config = configJsonSchema();
writeFileSync(
  target,
  `// Generated by scripts/engine-schemas.ts from @open-cr-agent/cli and core; do not edit.
export const CONFIG_SCHEMA_ID = ${JSON.stringify(config.$id)};
export const CONFIG_JSON_SCHEMA = ${JSON.stringify(config)};
export const RULES_JSON_SCHEMA = ${JSON.stringify(rules)};
`,
);
execFileSync("npx", ["biome", "format", "--write", target.pathname], { stdio: "inherit" });
