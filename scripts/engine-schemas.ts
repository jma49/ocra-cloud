// Writes src/engine-schemas.ts: the JSON Schema the engine reads a
// repository's .ocra/rules.json with, taken from the installed core package,
// so the Worker checks a console edit without loading core (the contract,
// which has .ocra/config.json's schema, has none for rules). Run with Node
// after bumping it:
// node scripts/engine-schemas.ts (test-node/engine-schemas.test.ts fails until then).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { repoRuleSchema } from "@open-cr-agent/core/internal";
import { z } from "zod";

const target = new URL("../src/engine-schemas.ts", import.meta.url);
const rules = z.toJSONSchema(z.object({ rules: z.array(repoRuleSchema) }), {
  target: "draft-2020-12",
  io: "input",
});
writeFileSync(
  target,
  `// Generated by scripts/engine-schemas.ts from @open-cr-agent/core; do not edit.
export const RULES_JSON_SCHEMA = ${JSON.stringify(rules)};
`,
);
execFileSync("npx", ["biome", "format", "--write", target.pathname], { stdio: "inherit" });
